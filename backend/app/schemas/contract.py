"""Request and response schemas for contract records.

System-managed values are deliberately absent from the request schemas:
the database ID, contract number, creator, and timestamps are generated by
the API. ``extra="forbid"`` makes a client attempt to set one of those fields
a validation error instead of silently ignoring it.
"""

from datetime import date, datetime
from decimal import Decimal
from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator

from app.models.enums import ContractStatus

# ISO 4217 currency codes are three letters. The application stores the code
# in uppercase and lets PostgreSQL enforce the column width.
CURRENCY_PATTERN = r"^[A-Za-z]{3}$"


class ContractBase(BaseModel):
    """Fields shared by contract creation and update requests."""

    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)

    title: str = Field(min_length=1, max_length=255)
    contract_type: str = Field(min_length=1, max_length=64)
    counterparty_name: str = Field(min_length=1, max_length=255)
    description: str | None = Field(default=None, max_length=10_000)
    contract_value: Decimal | None = Field(
        default=None,
        ge=0,
        max_digits=18,
        decimal_places=2,
    )
    currency: str = Field(
        default="INR",
        min_length=3,
        max_length=3,
        pattern=CURRENCY_PATTERN,
    )
    start_date: date | None = None
    end_date: date | None = None

    @field_validator("currency")
    @classmethod
    def normalize_currency(cls, value: str) -> str:
        return value.upper()

    @field_validator("description")
    @classmethod
    def normalise_description(cls, value: str | None) -> str | None:
        # An empty description is stored as NULL rather than an empty string.
        if value is None:
            return None
        return value.strip() or None

    @model_validator(mode="after")
    def validate_date_range(self) -> "ContractBase":
        if (
            self.start_date is not None
            and self.end_date is not None
            and self.end_date < self.start_date
        ):
            raise ValueError("end_date must be on or after start_date")
        return self


class ContractCreate(ContractBase):
    """Payload for creating a contract.

    New contracts always start as drafts. Status can be changed through the
    update endpoint, subject to the same access rules.
    """


class ContractUpdate(BaseModel):
    """Partial payload for updating a contract.

    Only fields in this schema can be changed. If a field is omitted, it keeps
    its current value. Explicit ``null`` clears nullable fields.
    """

    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)

    title: str | None = Field(default=None, min_length=1, max_length=255)
    contract_type: str | None = Field(default=None, min_length=1, max_length=64)
    counterparty_name: str | None = Field(
        default=None, min_length=1, max_length=255
    )
    description: str | None = Field(default=None, max_length=10_000)
    contract_value: Decimal | None = Field(
        default=None,
        ge=0,
        max_digits=18,
        decimal_places=2,
    )
    currency: str | None = Field(
        default=None,
        min_length=3,
        max_length=3,
        pattern=CURRENCY_PATTERN,
    )
    start_date: date | None = None
    end_date: date | None = None
    status: ContractStatus | None = None

    @field_validator("currency")
    @classmethod
    def normalize_currency(cls, value: str | None) -> str | None:
        return value.upper() if value is not None else None

    @field_validator("description")
    @classmethod
    def normalise_description(cls, value: str | None) -> str | None:
        if value is None:
            return None
        return value.strip() or None

    @model_validator(mode="after")
    def validate_payload(self) -> "ContractUpdate":
        if not self.model_fields_set:
            raise ValueError("Provide at least one field to update")

        # These columns are NOT NULL in the database, so an explicit null is
        # a client error rather than a request to clear them.
        for field_name in (
            "title",
            "contract_type",
            "counterparty_name",
            "currency",
            "status",
        ):
            if (
                field_name in self.model_fields_set
                and getattr(self, field_name) is None
            ):
                raise ValueError(f"{field_name} cannot be null")

        return self


class ContractRead(BaseModel):
    """A contract as returned by the API."""

    model_config = ConfigDict(from_attributes=True)

    id: UUID
    contract_number: str
    title: str
    contract_type: str
    counterparty_name: str
    description: str | None
    contract_value: Decimal | None
    currency: str
    start_date: date | None
    end_date: date | None
    status: ContractStatus
    created_by: UUID
    created_by_name: str | None = Field(
        default=None,
        description="Display name of the user who created the contract.",
    )
    created_at: datetime
    updated_at: datetime


class ContractListResponse(BaseModel):
    """Paginated contract list."""

    items: list[ContractRead]
    total: int = Field(description="Number of contracts matching the filters.")
    page: int
    page_size: int
    pages: int
